import { readFile } from 'node:fs/promises';

/** Resolve the small wire-schema vocabulary; reject unsupported generator input. */
export async function generateControlSchema() {
  const schema = JSON.parse(await readFile('protocol/control-messages.json', 'utf8'));
  if (schema.version !== 1) throw new Error('Unsupported control schema version');
  const targets = ['server', 'receiver', 'sender'];
  const rules = {};
  for (const [name, definition] of Object.entries(schema.fieldTypes)) {
    const rule = { ...definition };
    if (rule.source) {
      if (!['error-codes.json', 'close-reasons.json'].includes(rule.source))
        throw new Error(`Unknown enum source: ${name}`);
      const source = JSON.parse(await readFile(`protocol/${rule.source}`, 'utf8'));
      rule.values = Array.isArray(source) ? source : Object.keys(source);
      delete rule.source;
    }
    const keys = Object.keys(rule).sort().join(',');
    if (
      rule.kind === 'base64url' &&
      keys === 'bytes,kind' &&
      Number.isSafeInteger(rule.bytes) &&
      rule.bytes > 0
    ) {
      rules[name] = rule;
    } else if (
      rule.kind === 'integer' &&
      keys === 'kind,max,min' &&
      Number.isSafeInteger(rule.min) &&
      Number.isSafeInteger(rule.max) &&
      rule.min <= rule.max
    ) {
      rules[name] = rule;
    } else if (
      rule.kind === 'enum' &&
      keys === 'kind,values' &&
      Array.isArray(rule.values) &&
      rule.values.length &&
      rule.values.every((value) => typeof value === 'string') &&
      new Set(rule.values).size === rule.values.length
    ) {
      rules[name] = rule;
    } else throw new Error(`Invalid control field type: ${name}`);
  }
  for (const message of schema.messages) {
    if (
      typeof message.type !== 'string' ||
      !message.type ||
      !Array.isArray(message.targets) ||
      !message.targets.length ||
      message.targets.some((target) => !targets.includes(target)) ||
      new Set(message.targets).size !== message.targets.length ||
      !message.fields ||
      typeof message.fields !== 'object' ||
      Array.isArray(message.fields)
    )
      throw new Error('Invalid control message schema');
    for (const [field, rule] of Object.entries(message.fields)) {
      if (['v', 'type'].includes(field) || !Object.hasOwn(rules, rule))
        throw new Error(`Invalid field ${message.type}.${field}`);
    }
  }
  const quoted = (value) => JSON.stringify(value);
  const tsType = (name) =>
    rules[name].kind === 'integer'
      ? 'number'
      : rules[name].kind === 'base64url'
        ? 'string'
        : rules[name].values.map(quoted).join(' | ');
  const ts = `// Generated by scripts/generate-protocol.mjs. Do not edit.
export type ControlTarget = 'server' | 'receiver' | 'sender';
export type ControlFieldRule =
  | { kind: 'base64url'; bytes: number }
  | { kind: 'integer'; min: number; max: number }
  | { kind: 'enum'; values: readonly string[] };
export type ControlSchema = { type: string; targets: readonly ControlTarget[]; fields: Readonly<Record<string, string>> };
export const CONTROL_FIELD_TYPES: Readonly<Record<string, ControlFieldRule>> = ${JSON.stringify(rules, null, 2)};
export const CONTROL_SCHEMAS: readonly ControlSchema[] = ${JSON.stringify(schema.messages, null, 2)};
export type ControlMessage =
${schema.messages
  .map(
    (message) =>
      `  | { v: 1; type: ${quoted(message.type)}; ${Object.entries(message.fields)
        .map(([field, rule]) => `${field}: ${tsType(rule)};`)
        .join(' ')} }`,
  )
  .join('\n')};
`;
  const goKeyWidth = Math.max(...Object.keys(rules).map((name) => quoted(name).length)) + 2;
  const go = `// Code generated by scripts/generate-protocol.mjs; DO NOT EDIT.
package client

var controlFieldTypes = map[string]controlFieldRule{
${Object.entries(rules)
  .map(
    ([name, rule]) =>
      `\t${`${quoted(name)}:`.padEnd(goKeyWidth)}{kind: ${quoted(rule.kind)}, ${rule.kind === 'base64url' ? `bytes: ${rule.bytes}` : rule.kind === 'integer' ? `min: ${rule.min}, max: ${rule.max}` : `values: []string{${rule.values.map(quoted).join(', ')}}`}},`,
  )
  .join('\n')}
}

var controlSchemas = []controlSchema{
${schema.messages
  .map(
    (message) =>
      `\t{kind: ${quoted(message.type)}, targets: []string{${message.targets.map(quoted).join(', ')}}, fields: map[string]string{${Object.entries(
        message.fields,
      )
        .map(([field, rule]) => `${quoted(field)}: ${quoted(rule)}`)
        .join(', ')}}},`,
  )
  .join('\n')}
}
`;
  return {
    'packages/protocol/src/control.generated.ts': ts,
    'cli/internal/client/control_generated.go': go,
  };
}
