import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { generateControlSchema } from './control-schema.mjs';
process.chdir(fileURLToPath(new URL('../', import.meta.url)));
const constants = JSON.parse(
  await readFile(new URL('../protocol/constants.json', import.meta.url), 'utf8'),
);
const sharedConstants = JSON.parse(
  await readFile(new URL('../protocol/shared-constants.json', import.meta.url), 'utf8'),
);
const sharedErrors = JSON.parse(await readFile('protocol/shared-error-codes.json', 'utf8'));
const sharedControl = JSON.parse(await readFile('protocol/shared-control-messages.json', 'utf8'));
if (
  sharedControl.version !== 1 ||
  !Array.isArray(sharedControl.messages) ||
  sharedControl.messages.some(
    (message) =>
      !message ||
      typeof message.type !== 'string' ||
      !Array.isArray(message.targets) ||
      message.targets.some((target) => !['server', 'controller', 'member'].includes(target)) ||
      !Array.isArray(message.fields) ||
      message.fields.some((field) => typeof field !== 'string' || ['v', 'type'].includes(field)) ||
      (message.when !== undefined &&
        (!message.when ||
          typeof message.when !== 'object' ||
          Array.isArray(message.when) ||
          Object.values(message.when).some((value) => typeof value !== 'string'))),
  )
)
  throw new Error('Invalid shared control schema');
const errors = JSON.parse(await readFile('protocol/error-codes.json', 'utf8'));
const reasons = JSON.parse(await readFile('protocol/close-reasons.json', 'utf8'));
const outputs = {
  ...(await generateControlSchema()),
  'packages/protocol/src/constants.ts':
    '// Generated by scripts/generate-protocol.mjs. Do not edit.\nexport const C = ' +
    JSON.stringify(constants, null, 2) +
    ' as const;\nexport const ERROR_CODES = ' +
    JSON.stringify(errors, null, 2) +
    ' as const;\nexport const CLOSE_REASONS = ' +
    JSON.stringify(reasons, null, 2) +
    ' as const;\n',
  'packages/protocol/src/shared-constants.ts':
    '// Generated by scripts/generate-protocol.mjs. Do not edit.\nexport const SC = ' +
    JSON.stringify(sharedConstants, null, 2) +
    ' as const;\nexport const SHARED_ERROR_CODES = ' +
    JSON.stringify(sharedErrors, null, 2) +
    ' as const;\n',
  'packages/protocol/src/shared-control.generated.ts':
    '// Generated by scripts/generate-protocol.mjs. Do not edit.\n' +
    'export const SHARED_CONTROL_SCHEMAS = ' +
    JSON.stringify(sharedControl.messages, null, 2) +
    ' as const;\n',
  'cli/internal/constants/generated.go':
    '// Code generated by scripts/generate-protocol.mjs; DO NOT EDIT.\npackage constants\n\n' +
    Object.entries(constants)
      .map(([k, v]) => `const ${k} = ${v}`)
      .join('\n') +
    '\n\n' +
    errors.map((code) => `const CODE_${code} = "${code}"`).join('\n') +
    '\n',
};
for (const [path, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8').catch(() => '')) !== content)
      throw new Error(`Regenerate ${path}`);
  } else {
    await mkdir(path.slice(0, path.lastIndexOf('/')), { recursive: true });
    await writeFile(path, content);
  }
}
