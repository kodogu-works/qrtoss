export const dictionaries = { en, ja, es };
export type Language = keyof typeof dictionaries;
export function chooseLanguage(preferences: readonly string[], saved?: string | null): Language {
  if (saved && saved in dictionaries) return saved as Language;
  for (const value of preferences) {
    const base = value.toLowerCase().split('-')[0];
    if (base && base in dictionaries) return base as Language;
  }
  return 'en';
}
export function translate(
  language: Language,
  key: Key,
  values: Record<string, string | number> = {},
): string {
  return dictionaries[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? ''),
  );
}

